-- MessenJ schema starter: compare with your existing tables before running.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  full_name text,
  avatar_url text,
  bio text,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  content text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.statuses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text,
  media_url text,
  media_type text,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;
alter table public.statuses enable row level security;

drop policy if exists "profiles readable by authenticated" on public.profiles;
create policy "profiles readable by authenticated" on public.profiles for select to authenticated using (true);
drop policy if exists "users insert own profile" on public.profiles;
create policy "users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "participants read messages" on public.messages;
create policy "participants read messages" on public.messages for select to authenticated using (auth.uid() = sender_id or auth.uid() = receiver_id);
drop policy if exists "sender sends own messages" on public.messages;
create policy "sender sends own messages" on public.messages for insert to authenticated with check (auth.uid() = sender_id and sender_id <> receiver_id);
drop policy if exists "sender deletes own messages" on public.messages;
create policy "sender deletes own messages" on public.messages for delete to authenticated using (auth.uid() = sender_id);

drop policy if exists "authenticated read statuses" on public.statuses;
create policy "authenticated read statuses" on public.statuses for select to authenticated using (true);
drop policy if exists "users create own statuses" on public.statuses;
create policy "users create own statuses" on public.statuses for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "users update own statuses" on public.statuses;
create policy "users update own statuses" on public.statuses for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "users delete own statuses" on public.statuses;
create policy "users delete own statuses" on public.statuses for delete to authenticated using (auth.uid() = user_id);

create index if not exists messages_conversation_created_idx on public.messages (sender_id, receiver_id, created_at);
create index if not exists statuses_created_idx on public.statuses (created_at desc);
